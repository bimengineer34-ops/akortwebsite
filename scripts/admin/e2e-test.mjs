const call = async (method, p, body, raw) => {
  const headers = { Cookie: cookie, ...(method !== 'GET' ? { 'X-CSRF-Token': csrf } : {}) };
  const payload = raw ?? (body !== undefined ? JSON.stringify(body) : undefined);
  if (body !== undefined && !raw) headers['Content-Type'] = 'application/json';
  const r = await fetch(B + p, { method, headers, body: payload, redirect: 'manual' });
  const sc = r.headers.get('set-cookie');
  if (sc) cookie = sc.split(';')[0];
  const ct = r.headers.get('content-type') ?? '';
  const data = ct.includes('json') ? await r.json() : await r.text();
  return { status: r.status, data };
};
